// Builds seed.sql from scripts/seed-data.mjs and validates every question with the real engine.
import { writeFileSync } from 'node:fs';
import { MODE1, MODE2, MODE3, MODE1_MORE, MODE2_MORE, MODE3_MORE, VERBS } from './seed-data.mjs';
import { M1_SET3, M2_SET3 } from './seed-set3-m1m2.mjs';
import { M3_SET3 } from './seed-set3-m3.mjs';
import { corrupt } from './corrupt.mjs';
import { stripToPrompt, buildSlots, checkMode1 } from '../src/engine.js';
import { BANNED, formsOf } from '../src/verbs.js';
import { TAGS } from '../src/rules.js';

const esc = (s) => String(s).replace(/'/g, "''");
const now = Date.now();
const out = ['-- Generated by scripts/make-seed.mjs. Verbs use fixed ids with INSERT OR IGNORE; questions are added only if not already present, so this file is safe to re-run.'];
let problems = 0;
const bad = (m) => {
  console.error('SEED PROBLEM:', m);
  problems++;
};

// ----- verbs -----
let vid = 0;
const seen = new Set();
const addVerb = (base, past, tags, banned) => {
  if (seen.has(base)) return bad(`duplicate verb ${base}`);
  seen.add(base);
  for (const t of tags) if (!(t in TAGS)) bad(`unknown tag ${t} on ${base}`);
  vid++;
  out.push(`INSERT OR IGNORE INTO verbs (id, base, past, tags, banned, source, created_at) VALUES (${vid}, '${esc(base)}', '${esc(past)}', '${esc(JSON.stringify(tags))}', ${banned ? 1 : 0}, 'seed', ${now});`);
  for (const { form, kind } of formsOf(base, past)) {
    out.push(`INSERT OR IGNORE INTO verb_forms (form, verb_id, kind) VALUES ('${esc(form)}', ${vid}, '${kind}');`);
  }
};
for (const [b, p] of BANNED) addVerb(b, p, [], true);
for (const v of VERBS) addVerb(v.base, v.past, v.tags, false);

// ----- questions -----
// Questions are inserted with NO fixed id and only when the same question is not already in the table
// (matched by its content). That makes the file safe to run on a fresh database, on one seeded with the
// first 35 questions, on one with teacher-added questions, or twice in a row.
const curl = (s) => {
  let open = true;
  let out = '';
  for (const ch of s) {
    if (ch === '"') {
      out += open ? '“' : '”';
      open = !open;
    } else if (ch === "'") out += '’';
    else {
      out += ch;
      if (ch === '\n') open = true;
    }
  }
  return out;
};
const Q = []; // { mode, data }
const seenKey = new Set();
const addQ = (mode, data) => {
  const key = mode === 3 ? `3|${data.speaker}|${data.line}` : `${mode}|${data.correct}`;
  if (seenKey.has(key)) return bad(`duplicate question: ${key}`);
  seenKey.add(key);
  Q.push({ mode, data });
};

const doM1 = (list) => {
  for (const q of list) {
    const data = { correct: q.correct, prompt: stripToPrompt(q.correct, { lowerFirstSpoken: !!q.lowerFirst }) };
    if (!checkMode1(data, q.correct).correct) bad(`mode1 key does not mark itself correct: ${q.correct}`);
    if (checkMode1(data, data.prompt).correct) bad(`mode1 prompt already correct: ${q.correct}`);
    addQ(1, data);
  }
};
const doM2 = (list) => {
  for (const q of list) {
    const r = buildSlots(q.correct, q.faulty);
    if (!r.valid) bad(`mode2 invalid (${r.reason}): ${q.correct}`);
    addQ(2, { correct: q.correct, faulty: q.faulty });
  }
};
const doM3 = (list) => {
  for (const q of list) {
    for (const t of q.target) if (!(t in TAGS)) bad(`unknown tag ${t}`);
    const n = VERBS.filter((v) => v.tags.some((t) => q.target.includes(t))).length;
    if (n < 5) bad(`only ${n} verbs in the bank fit ${q.speaker}: ${q.target}`);
    if (!/[,.!?]$/.test(q.line)) bad(`mode3 line must end in punctuation: ${q.line}`);
    addQ(3, { speaker: q.speaker, line: q.line, context: q.context, target: q.target });
  }
};

// Original set 1 (ids 1-35 on a fresh database), then set 2, then set 3.
doM1(MODE1);
doM2(MODE2);
doM3(MODE3);
doM1(MODE1_MORE);
doM2(MODE2_MORE);
doM3(MODE3_MORE);

// Set 3
const set3m1 = M1_SET3.map((raw, i) => {
  const correct = curl(raw);
  const first = (correct.match(/“(\S+)/) || [])[1] || '';
  const eligible = !/^I(’|$)/.test(first);
  return { correct, lowerFirst: eligible && i % 3 !== 0 };
});
doM1(set3m1);

const profileUse = {};
const set3m2 = [];
M2_SET3.forEach((raw, i) => {
  const correct = curl(raw);
  const res = corrupt(correct, i, (f) => {
    const r = buildSlots(correct, f);
    return r.valid && r.slots.length >= 2 && r.slots.length <= 7;
  });
  if (!res) return bad(`could not make a faulty version for: ${correct}`);
  profileUse[res.profile] = (profileUse[res.profile] || 0) + 1;
  set3m2.push({ correct, faulty: res.faulty });
});
doM2(set3m2);

doM3(M3_SET3.map(([speaker, line, context, target]) => ({ speaker: curl(speaker), line: curl(line), context: curl(context), target })));

// uniqueness of what pupils actually see
const seeP = new Set();
const seeF = new Set();
for (const { mode, data } of Q) {
  if (mode === 1) {
    if (seeP.has(data.prompt)) bad(`duplicate Mode 1 prompt: ${data.prompt}`);
    seeP.add(data.prompt);
  }
  if (mode === 2) {
    if (seeF.has(data.faulty)) bad(`duplicate Mode 2 faulty text: ${data.faulty}`);
    seeF.add(data.faulty);
  }
}
const counts = { 1: 0, 2: 0, 3: 0 };
for (const { mode } of Q) counts[mode]++;
const TARGET = Number(process.env.MIN_PER_MODE || 150);
for (const m of [1, 2, 3]) if (counts[m] < TARGET) bad(`Mode ${m} has ${counts[m]} questions, wanted at least ${TARGET}`);

// SQL
const qsql = [];
for (const { mode, data } of Q) {
  const where =
    mode === 3
      ? `json_extract(data, '$.speaker') = '${esc(data.speaker)}' AND json_extract(data, '$.line') = '${esc(data.line)}'`
      : `json_extract(data, '$.correct') = '${esc(data.correct)}'`;
  qsql.push(`INSERT INTO questions (mode, class_id, public, active, data, created_at) SELECT ${mode}, NULL, 1, 1, '${esc(JSON.stringify(data))}', ${now} WHERE NOT EXISTS (SELECT 1 FROM questions WHERE mode = ${mode} AND ${where});`);
}
const qHeader = [
  `-- Dialogue Dash question bank: ${Q.length} questions (${counts[1]} Mode 1, ${counts[2]} Mode 2, ${counts[3]} Mode 3).`,
  '-- Run AFTER schema.sql. Safe to run on a fresh database, on one that already has questions 1-35,',
  '-- on one with questions your teachers added, and any number of times: a question is inserted only',
  '-- if the same question is not already in the table. Existing questions, ids and pupil results are never changed.',
];
writeFileSync(new URL('../questions-450.sql', import.meta.url), [...qHeader, ...qsql].join('\n') + '\n');
writeFileSync(new URL('../seed.sql', import.meta.url), [...out, ...qHeader.slice(0, 1), ...qsql].join('\n') + '\n');

// coverage report
const codeUse = {};
for (const { mode, data } of Q) {
  if (mode !== 2) continue;
  const r = buildSlots(data.correct, data.faulty);
  for (const sl of r.slots) for (const e of sl.errors) codeUse[e.code] = (codeUse[e.code] || 0) + 1;
}
const spotHist = {};
for (const { mode, data } of Q) if (mode === 2) { const n = buildSlots(data.correct, data.faulty).slots.length; spotHist[n] = (spotHist[n] || 0) + 1; }
console.log('Mode 2 distinct fault recipes:', Object.keys(profileUse).length, '| mistake spots per question:', JSON.stringify(spotHist), '| error codes:', JSON.stringify(codeUse));
console.log(`questions-450.sql and seed.sql written: ${vid} verbs; questions ${Q.length} = ${counts[1]} / ${counts[2]} / ${counts[3]}.`);
if (problems) {
  console.error(`${problems} problem(s).`);
  process.exit(1);
}
