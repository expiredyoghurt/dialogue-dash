// Builds seed.sql from scripts/seed-data.mjs and validates every question with the real engine.
import { writeFileSync } from 'node:fs';
import { MODE1, MODE2, MODE3, VERBS } from './seed-data.mjs';
import { stripToPrompt, buildSlots, checkMode1 } from '../src/engine.js';
import { BANNED, formsOf } from '../src/verbs.js';
import { TAGS } from '../src/rules.js';

const esc = (s) => String(s).replace(/'/g, "''");
const now = Date.now();
const out = ['-- Generated by scripts/make-seed.mjs. Safe to re-run: uses fixed ids with INSERT OR IGNORE.'];
let problems = 0;
const bad = (m) => {
  console.error('SEED PROBLEM:', m);
  problems++;
};

// ----- verbs -----
let vid = 0;
const seen = new Set();
const addVerb = (base, past, tags, banned) => {
  if (seen.has(base)) return bad(`duplicate verb ${base}`);
  seen.add(base);
  for (const t of tags) if (!(t in TAGS)) bad(`unknown tag ${t} on ${base}`);
  vid++;
  out.push(`INSERT OR IGNORE INTO verbs (id, base, past, tags, banned, source, created_at) VALUES (${vid}, '${esc(base)}', '${esc(past)}', '${esc(JSON.stringify(tags))}', ${banned ? 1 : 0}, 'seed', ${now});`);
  for (const { form, kind } of formsOf(base, past)) {
    out.push(`INSERT OR IGNORE INTO verb_forms (form, verb_id, kind) VALUES ('${esc(form)}', ${vid}, '${kind}');`);
  }
};
for (const [b, p] of BANNED) addVerb(b, p, [], true);
for (const v of VERBS) addVerb(v.base, v.past, v.tags, false);

// ----- questions -----
let qid = 0;
const addQ = (mode, data) => {
  qid++;
  out.push(`INSERT OR IGNORE INTO questions (id, mode, class_id, public, active, data, created_at) VALUES (${qid}, ${mode}, NULL, 1, 1, '${esc(JSON.stringify(data))}', ${now});`);
};

for (const q of MODE1) {
  const data = { correct: q.correct, prompt: stripToPrompt(q.correct, { lowerFirstSpoken: !!q.lowerFirst }) };
  if (!checkMode1(data, q.correct).correct) bad(`mode1 key does not mark itself correct: ${q.correct}`);
  if (checkMode1(data, data.prompt).correct) bad(`mode1 prompt already correct: ${q.correct}`);
  addQ(1, data);
}
for (const q of MODE2) {
  const r = buildSlots(q.correct, q.faulty);
  if (!r.valid) bad(`mode2 invalid (${r.reason}): ${q.correct}`);
  addQ(2, { correct: q.correct, faulty: q.faulty });
}
for (const q of MODE3) {
  for (const t of q.target) if (!(t in TAGS)) bad(`unknown tag ${t}`);
  addQ(3, { speaker: q.speaker, line: q.line, context: q.context, target: q.target });
}

writeFileSync(new URL('../seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`seed.sql written: ${vid} verbs, ${qid} questions (${MODE1.length} / ${MODE2.length} / ${MODE3.length}).`);
if (problems) {
  console.error(`${problems} problem(s).`);
  process.exit(1);
}
